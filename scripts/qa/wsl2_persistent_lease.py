"""PLAT-002D-RECOVERY: test-only *persistent* Linux lease ledger.

No model, agent, network, process spawn/kill, production config or
automatic retry. A narrowly gated --prepare may only create a new,
0700 user-owned QA journal below the local Linux guest home (not /tmp
or Windows DrvFs). --inspect is independent and read-only.
Terminal evidence is read/validated, NOT generated by this module:
a future separately accepted test-owned guardian must prove its own
waitpid/process tree teardown before authoring such a record.

Offline parsers and state-classifier never claim a real sandbox or
successful external effect. Linux-native writing is NOT tested here.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
try:
    import pwd
except ImportError:  # offline Windows contract tests only, never Linux launch
    pwd=None
import re
import stat
import sys
import time

VERSION=1
KIND='alaz.wsl2.test-only-persistent-lease.v1'
DIR_NAME='.alazharness-qa-lease-v1'
EXTERNAL_OUTCOME='UNKNOWN_DO_NOT_REPLAY'
TTL_SECONDS=7
MAX_FRAME=4096
RUN_PATTERN=r'[0-9a-f]{24}'
SHA_PATTERN=r'[0-9a-f]{64}'
BOOT_PATTERN=r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
BASE_FIELDS=frozenset({
    'version','kind','phase','runId','nonceSha256','sourceSha256',
    'bootId','guestUid','issuedBoottimeNs','expiresBoottimeNs',
    'issuerPid','issuerStartTick','externalEffectOutcome',
    'agentToolStarted','realModelCalls','fullD3BAccepted',
})
PID_FIELDS=frozenset({
    'guardianPid','guardianStartTick','workerPid','workerStartTick',
    'grandchildPid','grandchildStartTick',
})
TERMINAL_FIELDS=frozenset({
    'terminalBoottimeNs','terminalState','leaseExpired',
    'ownedWorkerReaped','ownedGrandchildReaped','cleanupVerified',
})
PHASE_FILES={'PREPARED':'prepare.json','READY':'ready.json',
             'TERMINAL':'terminal.json'}
SCHEMAS={
  'PREPARED':BASE_FIELDS,
  'READY':BASE_FIELDS|PID_FIELDS,
  'TERMINAL':BASE_FIELDS|PID_FIELDS|TERMINAL_FIELDS,
}

class LedgerRejected(ValueError):
    def __init__(self,code):
        super().__init__(code)
        self.code=code

def require(ok,code):
    if not ok:raise LedgerRejected(code)

def is_hex(value,n):
    return (n in (24,64) and type(value) is str
            and re.fullmatch(RUN_PATTERN if n==24 else SHA_PATTERN,
                             value) is not None)

def is_int(value,min_value=0,max_value=(1<<63)-1):
    return type(value) is int and min_value<=value<=max_value

def parse_object(pairs):
    result={}
    for key,value in pairs:
        require(key not in result,'DUPLICATE_RECORD_KEY')
        result[key]=value
    return result

def reject_json_constant(_):
    raise LedgerRejected('NONFINITE_JSON_NOT_ALLOWED')

def encode_frame(value):
    require(type(value) is dict,'FRAME_OBJECT_REQUIRED')
    raw=(json.dumps(value,sort_keys=True,separators=(',',':'),
                    ensure_ascii=True,allow_nan=False)+'\n').encode('ascii')
    require(0<len(raw)<=MAX_FRAME,'FRAME_TOO_LARGE')
    return raw

def decode_frame(raw):
    require(type(raw) is bytes and 0<len(raw)<=MAX_FRAME,
            'INVALID_FRAME_SIZE')
    require(raw.endswith(b'\n') and raw.count(b'\n')==1 and
            b'\r' not in raw and b'\x00' not in raw,
            'INVALID_FRAME_TERMINATOR')
    try:
        record=json.loads(raw.decode('utf-8'),
                          object_pairs_hook=parse_object,
                          parse_constant=reject_json_constant)
    except (UnicodeDecodeError,json.JSONDecodeError):
        raise LedgerRejected('INVALID_RECORD_JSON') from None
    require(type(record) is dict,'RECORD_OBJECT_REQUIRED')
    return record

def validate_record(record,phase):
    require(phase in SCHEMAS,'UNSUPPORTED_LEDGER_PHASE')
    require(type(record) is dict and set(record)==SCHEMAS[phase],
            'RECORD_SCHEMA_FIELDS')
    require(type(record['version']) is int and record['version']==VERSION
            and type(record['kind']) is str and record['kind']==KIND
            and type(record['phase']) is str and record['phase']==phase,
            'RECORD_VERSION_PHASE')
    require(is_hex(record['runId'],24) and
            is_hex(record['nonceSha256'],64) and
            is_hex(record['sourceSha256'],64) and
            type(record['bootId']) is str and
            re.fullmatch(BOOT_PATTERN,record['bootId']) is not None,
            'RECORD_IDENTITY_INVALID')
    require(is_int(record['guestUid'],1,65534)
            and is_int(record['issuerPid'],2,2147483646)
            and is_int(record['issuerStartTick'],1)
            and is_int(record['issuedBoottimeNs'],1)
            and is_int(record['expiresBoottimeNs'],1)
            and record['expiresBoottimeNs']==
              record['issuedBoottimeNs']+TTL_SECONDS*1_000_000_000,
            'RECORD_LEASE_INVALID')
    require(record['externalEffectOutcome']==EXTERNAL_OUTCOME
            and type(record['externalEffectOutcome']) is str
            and record['agentToolStarted'] is False
            and type(record['realModelCalls']) is int
            and record['realModelCalls']==0
            and record['fullD3BAccepted'] is False,
            'RECORD_AUTHORITY_WIDENING')
    if phase in ('READY','TERMINAL'):
        for key in PID_FIELDS:
            require(is_int(record[key],1,1<<63),'PROCESS_IDENTITY_MALFORMED')
        pids=(record['guardianPid'],record['workerPid'],
              record['grandchildPid'])
        require(len(set(pids))==3 and
                all(pid>1 and pid<=2147483646 for pid in pids),
                'PROCESS_PID_COLLISION')
    if phase=='TERMINAL':
        require(record['terminalState']=='LEASE_EXPIRED_EXTERNAL_OUTCOME_UNKNOWN'
                and type(record['terminalState']) is str
                and is_int(record['terminalBoottimeNs'],1)
                and record['terminalBoottimeNs']>=record['expiresBoottimeNs']
                and record['leaseExpired'] is True
                and record['ownedWorkerReaped'] is True
                and record['ownedGrandchildReaped'] is True
                and record['cleanupVerified'] is True,
                'TERMINAL_CLOSURE_NOT_PROVEN')
    return record

def shared_identity(record):
    return {k:record[k] for k in BASE_FIELDS if k!='phase'}

def assert_bound(prepared,next_record):
    require(shared_identity(prepared)==shared_identity(next_record),
            'RUN_OR_LEASE_IDENTITY_DRIFT')
    return True

def snapshot_state(prepared,ready,terminal,current):
    """Conservative independent audit. Never calls OS, performs I/O or acts."""
    validate_record(prepared,'PREPARED')
    if ready is not None:
        validate_record(ready,'READY')
        assert_bound(prepared,ready)
    if terminal is not None:
        validate_record(terminal,'TERMINAL')
        assert_bound(prepared,terminal)
        require(ready is not None,'TERMINAL_WITHOUT_READY')
        for key in PID_FIELDS:
            require(ready[key]==terminal[key],'PID_BIRTH_TICK_CHANGED')
    require(type(current) is dict and
            set(current)=={'bootId','boottimeNs','trackedPidsInspected',
                           'processes','fsType'},
            'INSPECTION_FIELDS')
    require(type(current['bootId']) is str and
            re.fullmatch(BOOT_PATTERN,current['bootId']) is not None
            and is_int(current['boottimeNs'],1)
            and type(current['trackedPidsInspected']) is bool
            and type(current['processes']) is dict
            and current['fsType']=='ext4' and
            type(current['fsType']) is str,
            'UNTRUSTED_INSPECTION')
    base={'externalEffectOutcome':EXTERNAL_OUTCOME,
          'automaticRetry':False,'processLaunchAuthorized':False,
          'fullD3BAccepted':False,'realModelCalls':0,
          'nativeSecurityAccepted':False,
          'independentOrphanClosureVerified':False}
    if current['bootId']!=prepared['bootId']:
        status='BOOT_CHANGED_UNKNOWN'
    elif not current['trackedPidsInspected']:
        status='INCOMPLETE_TRACKED_PID_INSPECTION_UNKNOWN'
    elif current['boottimeNs']<prepared['expiresBoottimeNs']:
        status='LEASE_ACTIVE_OR_CLOCK_UNKNOWN'
    elif terminal is None:
        status='LEASE_EXPIRED_TERMINAL_MISSING_UNKNOWN'
    else:
        states=[]
        for key in ('guardian','worker','grandchild'):
            pid=terminal[key+'Pid']
            name=str(pid)
            require(name in current['processes'],'PROCESS_SCAN_NOT_BOUND_TO_PIDS')
            observed=current['processes'][name]
            if observed is None:
                states.append('ABSENT')
                continue
            require(type(observed) is dict and
                    set(observed)=={'startTick','state'} and
                    is_int(observed['startTick'],1)
                    and type(observed['state']) is str and
                    observed['state'] in ('R','S','D','T','Z','I'),
                    'PROC_IDENTITY_UNTRUSTED')
            states.append('PID_REUSED' if
                observed['startTick']!=terminal[key+'StartTick']
                else 'PID_STILL_PRESENT')
        if 'PID_STILL_PRESENT' in states:
            status='TEST_OWNED_PROCESS_STILL_PRESENT_UNKNOWN'
        elif 'PID_REUSED' in states:
            status='PID_REUSED_CLOSURE_UNKNOWN'
        elif current['boottimeNs']<terminal['terminalBoottimeNs']:
            status='TERMINAL_AFTER_INSPECTION_UNKNOWN'
        else:
            # Exact known PIDs are absent. This does NOT prove that a
            # detached descendant with a DIFFERENT PID is absent.
            # Terminal assertions are same-UID QA data, not attestation.
            status='RECORDED_PIDS_ABSENT_ORPHAN_CLOSURE_UNPROVEN'
    return dict(base,state=status,
                runId=prepared['runId'],
                journalEvidenceOnly=True,
                bootBound=(current['bootId']==prepared['bootId']))

def _proc_start_tick(pid):
    raw=(Path('/proc')/str(pid)/'stat').read_text(encoding='ascii')
    tail=raw.rsplit(') ',1)[1].split()
    require(len(tail)>=20,'PROC_START_TICK_UNAVAILABLE')
    return int(tail[19])

def _boot_identity():
    raw=Path('/proc/sys/kernel/random/boot_id').read_text(encoding='ascii').strip().lower()
    require(re.fullmatch(BOOT_PATTERN,raw) is not None,'BOOT_ID_NOT_AVAILABLE')
    return raw

def _boottime_ns():
    require(hasattr(time,'CLOCK_BOOTTIME'),'CLOCK_BOOTTIME_REQUIRED')
    return time.clock_gettime_ns(time.CLOCK_BOOTTIME)

def _mount_type(home):
    """Resolve longest /proc/self/mountinfo covering a user-home path."""
    target=str(home)
    choices=[]
    for line in Path('/proc/self/mountinfo').read_text(encoding='utf-8').splitlines():
        a,b=line.split(' - ',1)
        cols=a.split()
        mountpoint=cols[4]
        fstype=b.split()[0]
        if target==mountpoint or target.startswith(mountpoint.rstrip('/')+'/'):
            choices.append((len(mountpoint),fstype))
    require(bool(choices),'HOME_MOUNT_UNKNOWN')
    fs=max(choices)[1]
    require(fs=='ext4','PERSISTENT_EXT4_GUEST_HOME_REQUIRED')
    return fs

def _trusted_linux_home():
    require(sys.platform=='linux' and platform.machine()=='x86_64',
            'LINUX_X64_REQUIRED')
    require('microsoft' in platform.release().lower()
            and 'wsl2' in platform.release().lower(),
            'WSL2_GUEST_REQUIRED')
    require(pwd is not None,'LINUX_PWD_REQUIRED')
    uid=os.getuid()
    require(uid>0 and os.geteuid()==uid and
            os.getgid()==os.getegid(),'UNPRIVILEGED_IDENTITY_REQUIRED')
    home=Path(pwd.getpwuid(uid).pw_dir)
    require(home.is_absolute() and
            str(home).startswith('/home/') and
            len(home.parts)==3 and not home.is_symlink(),
            'TRUSTED_HOME_REQUIRED')
    meta=home.lstat()
    require(stat.S_ISDIR(meta.st_mode) and meta.st_uid==uid
            and home.resolve(strict=True)==home,'HOME_OWNER_OR_SYMLINK_REFUSED')
    _mount_type(home)
    return home

def _open_owned_directory(parent_fd,name,uid,*,create):
    """Open one directory component via verified parent dirfd.

    Never traverse a symlink or rely on Path.exists()+Path.open() race.
    If a run ID already exists, creation fails rather than replaying it.
    """
    require(type(name) is str and
            (name==DIR_NAME or
             (name.startswith('run-') and is_hex(name[4:],24))),
            'DIRECTORY_COMPONENT_NOT_ALLOWED')
    if create:
        os.mkdir(name,mode=0o700,dir_fd=parent_fd)
        os.fsync(parent_fd)
    flags=os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW|os.O_CLOEXEC
    handle=os.open(name,flags,dir_fd=parent_fd)
    try:
        meta=os.fstat(handle)
        require(stat.S_ISDIR(meta.st_mode)
                and stat.S_IMODE(meta.st_mode)==0o700
                and meta.st_uid==uid,
                'PRIVATE_LEDGER_FD_UNTRUSTED')
        return handle
    except BaseException:
        os.close(handle)
        raise

def _open_guest_home(home,uid):
    flags=os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW|os.O_CLOEXEC
    fd=os.open(home,flags)
    try:
        info=os.fstat(fd)
        require(stat.S_ISDIR(info.st_mode) and
                info.st_uid==uid,
                'HOME_DIRECTORY_IDENTITY_CHANGED')
        return fd
    except BaseException:
        os.close(fd)
        raise

def _durable_file(dir_fd,name,data):
    require(name in PHASE_FILES.values(),'WRITE_FILE_NOT_WHITELISTED')
    require(type(data) is bytes and 0<len(data)<=MAX_FRAME,
            'DURABLE_FRAME_SIZE_INVALID')
    flags=os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW|os.O_CLOEXEC
    fd=os.open(name,flags,0o600,dir_fd=dir_fd)
    try:
        meta=os.fstat(fd)
        require(stat.S_ISREG(meta.st_mode) and meta.st_nlink==1
                and meta.st_uid==os.getuid()
                and stat.S_IMODE(meta.st_mode)==0o600,
                'DURABLE_FILE_UNTRUSTED')
        written=0
        while written<len(data):
            count=os.write(fd,data[written:])
            require(type(count) is int and count>0,
                    'SHORT_DURABLE_WRITE')
            written+=count
        os.fsync(fd)
    finally:
        os.close(fd)
    os.fsync(dir_fd)

def _read_record(dir_fd,name,phase):
    require(name in PHASE_FILES.values(),'READ_FILE_NOT_WHITELISTED')
    fd=os.open(name,os.O_RDONLY|os.O_NOFOLLOW|os.O_CLOEXEC,
               dir_fd=dir_fd)
    try:
        stat_data=os.fstat(fd)
        require(stat.S_ISREG(stat_data.st_mode)
                and stat_data.st_nlink==1
                and stat_data.st_uid==os.getuid()
                and stat.S_IMODE(stat_data.st_mode)==0o600
                and 0<stat_data.st_size<=MAX_FRAME,
                'RECORD_FILE_OWNER_OR_MODE')
        raw=os.read(fd,MAX_FRAME+1)
    finally:
        os.close(fd)
    return validate_record(decode_frame(raw),phase)

def prepare_test_only(run_id,nonce_hash,source_hash):
    """Opt-in fixture PREPARED record only. No child or agent is run."""
    require(is_hex(run_id,24) and is_hex(nonce_hash,64)
            and is_hex(source_hash,64),'PREPARE_INPUT_INVALID')
    home=_trusted_linux_home()
    require(source_hash==hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            'SOURCE_SHA_NOT_THIS_TEST_MODULE')
    uid=os.getuid()
    hfd=_open_guest_home(home,uid)
    try:
        # One known QA directory may persist across runs. Its identity
        # is verified by a no-follow fd; an already-present run NEVER
        # permits overwriting/replaying a prepare file.
        try:
            rfd=_open_owned_directory(hfd,DIR_NAME,uid,create=True)
        except FileExistsError:
            rfd=_open_owned_directory(hfd,DIR_NAME,uid,create=False)
        try:
            dfd=_open_owned_directory(rfd,'run-'+run_id,uid,create=True)
            try:
                issued=_boottime_ns()
                record={'version':1,'kind':KIND,'phase':'PREPARED',
                    'runId':run_id,'nonceSha256':nonce_hash,
                    'sourceSha256':source_hash,'bootId':_boot_identity(),
                    'guestUid':uid,'issuedBoottimeNs':issued,
                    'expiresBoottimeNs':issued+TTL_SECONDS*1_000_000_000,
                    'issuerPid':os.getpid(),
                    'issuerStartTick':_proc_start_tick(os.getpid()),
                    'externalEffectOutcome':EXTERNAL_OUTCOME,
                    'agentToolStarted':False,'realModelCalls':0,
                    'fullD3BAccepted':False}
                validate_record(record,'PREPARED')
                _durable_file(dfd,'prepare.json',encode_frame(record))
            finally:
                os.close(dfd)
        finally:
            os.close(rfd)
    finally:
        os.close(hfd)
    return {'result':'PREPARED_TEST_ONLY_NO_WORKER',
            'runId':run_id,'externalEffectOutcome':EXTERNAL_OUTCOME,
            'durablePrepareWritten':True,
            'linuxProcessStarted':False,'realModelCalls':0,
            'fullD3BAccepted':False,'automaticRetry':False}

def _optional_record(dir_fd,name,phase):
    try:
        return _read_record(dir_fd,name,phase)
    except FileNotFoundError:
        return None

def _read_proc_identity(pid):
    try:
        text=(Path('/proc')/str(pid)/'stat').read_text(encoding='ascii')
        tail=text.rsplit(') ',1)[1].split()
        require(len(tail)>=20,'PROC_RECORD_INCOMPLETE')
        return {'state':tail[0],'startTick':int(tail[19])}
    except (FileNotFoundError,ProcessLookupError):
        return None

def inspect_test_only(run_id,nonce_hash,source_hash):
    """Read-only, fd-scoped QA inspection. Always fail closed."""
    require(is_hex(run_id,24) and is_hex(nonce_hash,64)
            and is_hex(source_hash,64),'INSPECT_INPUT_INVALID')
    home=_trusted_linux_home()
    uid=os.getuid()
    homefd=_open_guest_home(home,uid)
    try:
        try:
            rfd=_open_owned_directory(homefd,DIR_NAME,uid,create=False)
        except FileNotFoundError:
            return {'state':'NO_LEDGER_UNKNOWN','runId':run_id,
                    'externalEffectOutcome':EXTERNAL_OUTCOME,
                    'automaticRetry':False,'fullD3BAccepted':False}
        try:
            try:
                dfd=_open_owned_directory(rfd,'run-'+run_id,uid,create=False)
            except FileNotFoundError:
                return {'state':'NO_RUN_UNKNOWN','runId':run_id,
                        'externalEffectOutcome':EXTERNAL_OUTCOME,
                        'automaticRetry':False,'fullD3BAccepted':False}
            try:
                prepared=_read_record(dfd,'prepare.json','PREPARED')
                require(prepared['runId']==run_id and
                        prepared['nonceSha256']==nonce_hash and
                        prepared['sourceSha256']==source_hash,
                        'INSPECT_RUN_BINDING_MISMATCH')
                ready=_optional_record(dfd,'ready.json','READY')
                terminal=_optional_record(dfd,'terminal.json','TERMINAL')
            finally:os.close(dfd)
        finally:os.close(rfd)
    finally:os.close(homefd)
    proc={}
    for record in (ready,terminal):
        if record:
            for key in ('guardianPid','workerPid','grandchildPid'):
                pid=record[key]
                try:
                    proc[str(pid)]=_read_proc_identity(pid)
                except (PermissionError,OSError,IndexError,ValueError,
                        LedgerRejected):
                    return {'state':'PROC_UNREADABLE_UNKNOWN',
                            'externalEffectOutcome':EXTERNAL_OUTCOME,
                            'automaticRetry':False,'fullD3BAccepted':False}
    current={'bootId':_boot_identity(),'boottimeNs':_boottime_ns(),
             'trackedPidsInspected':True,'processes':proc,
             'fsType':_mount_type(home)}
    return snapshot_state(prepared,ready,terminal,current)

def main(argv=None):
    parser=argparse.ArgumentParser(allow_abbrev=False)
    parser.add_argument('--mode',required=True,choices=('inspect','prepare'))
    parser.add_argument('--run-id',required=True)
    parser.add_argument('--nonce-sha256',required=True)
    parser.add_argument('--source-sha256',required=True)
    try:
        args=parser.parse_args(argv)
        if args.mode=='prepare':
            require(os.environ.get('ALAZ_PLAT002D_PERSISTENT_QA')=='1',
                    'EXPLICIT_QA_PREPARE_OPTIN_REQUIRED')
            result=prepare_test_only(args.run_id,args.nonce_sha256,
                                     args.source_sha256)
        else:
            result=inspect_test_only(args.run_id,args.nonce_sha256,
                                     args.source_sha256)
        print(json.dumps(result,sort_keys=True,separators=(',',':')))
        return 0
    except Exception:
        # Strict fail-closed: no arbitrary paths, keys or exception
        # details are returned to a caller.
        print('{"state":"REFUSED","externalEffectOutcome":"UNKNOWN_DO_NOT_REPLAY",'
              '"automaticRetry":false,"fullD3BAccepted":false}')
        return 2

if __name__=='__main__':
    raise SystemExit(main())
