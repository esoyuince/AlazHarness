"""Authenticated loopback STORAGE-readiness HTTP, not the Hermes agent API.

Compose the canonical NativeStoreStartup once; never construct an API adapter,
second database owner, model or arbitrary request handler. Only GET /health/live
and GET /health/ready exist. These diagnostic routes do NOT authorize dispatch.
Caller retains ProfileLease until close() confirms both listener and stores.
Uncertain HTTP cleanup forbids store close/retry; terminate the owned process.
"""
from __future__ import annotations
import asyncio
import hmac
import re

import gateway_store_startup as startup


class ReadinessRejected(RuntimeError):
    pass


def require(ok,reason):
    if not ok:raise ReadinessRejected(reason)


def _web():
    # aiohttp imports its unused file-response machinery. For this JSON-only
    # service, seed the stdlib MIME database without optional OS mime files.
    # Python 3.12 prepends knownfiles even when init(files=[]) is specified.
    # knownfiles is public configuration; restore it, never change functions,
    # permissions, native source or the HTTP implementation.
    import mimetypes
    if not mimetypes.inited:
        previous=mimetypes.knownfiles
        try:
            mimetypes.knownfiles=[]
            mimetypes.init(files=[])
        finally:
            mimetypes.knownfiles=previous
    from aiohttp import web
    return web


class StorageReadinessHttp:
    """One-shot actor/event-loop-bound, read-only diagnostic service.

    The token is trusted local configuration, kept out of returned diagnostics.
    It must be randomly generated by the caller; shape validation is not proof
    of entropy. This class is NOT a public-facing/auth-provider HTTP Gateway.
    No self-healing after revoked readiness; establish a new lifecycle instead.
    """
    def __init__(self,stores,*,token,port=0):
        require(type(stores) is startup.NativeStoreStartup,'readiness_native_startup_required')
        require(getattr(stores,'_response_expected',None) is None,'readiness_three_store_not_qualified')
        require(type(token) is str and re.fullmatch('[0-9a-f]{64}',token) is not None,
                'readiness_local_token_required')
        require(type(port) is int and 0<=port<=65535,'readiness_loopback_port')
        require(stores.status()['state']=='NEW','readiness_fresh_startup_required')
        self._stores=stores;self._actor=startup.live.profiles._actor()
        self._authorization=('Bearer '+token).encode('ascii')
        self._requested_port=port;self._bound_port=None;self._loop=None
        self._stage='NEW';self._runner=None;self._site=None;self._http_gone=True
        self._web_module=None;self._expected=None;self._native=None;self._handles=None
        self._revoked=False;self._probes=0

    def _owned(self):
        require(startup.live.profiles._actor()==self._actor,'readiness_other_actor')
        loop=asyncio.get_running_loop()
        require(self._loop is None or loop is self._loop,'readiness_other_loop')
        return loop

    def _probe(self):
        self._owned()
        require(not self._revoked,'readiness_revoked')
        require(self._stores.status()['state']=='VERIFIED','readiness_storage_not_verified')
        self._stores._owned();self._stores._drained()
        state,replay=self._stores.state_store,self._stores.replay_store
        require(state is self._native[0] and replay is self._native[1]
                and state._conn is self._handles[0]
                and replay._conn is self._handles[1], 'readiness_store_handle_changed')
        require(self._stores.expectation==self._expected,'readiness_expectation_changed')
        proof=startup.live.verify_live_stores(self._stores._held,self._stores._mount,
                                             state,replay,self._expected)
        require(proof['state']=='NATIVE_STORE_CONNECTIONS_VERIFIED'
                and proof['epochObserved']==self._expected.epoch
                and proof['runtimeAdmissionAuthorized'] is False,
                'readiness_live_result')
        self._probes+=1

    async def start(self):
        self._loop=self._owned()
        require(self._stage=='NEW','readiness_not_fresh')
        self._stage='STARTING'
        try:
            proof=self._stores.start()
            require(proof['state']=='VERIFIED' and proof['storageReady'] is True,
                    'readiness_startup_result')
            self._expected=self._stores.expectation
            self._native=(self._stores.state_store,self._stores.replay_store)
            self._handles=tuple(store._conn for store in self._native)
            self._probe()  # Revalidate immediately before ANY listener construction.
            web=self._web_module=_web()
            app=web.Application(client_max_size=1024)
            app.router.add_route('*','/{tail:.*}',self._handle)
            self._runner=web.AppRunner(app,access_log=None,handle_signals=False,
                shutdown_timeout=2.0,keepalive_timeout=2.0,auto_decompress=False,
                max_line_size=2048,max_field_size=2048,max_headers=32)
            # Keep cleanup uncertain until runner.cleanup has actually returned.
            self._http_gone=False
            await self._runner.setup()
            self._site=web.TCPSite(self._runner,'127.0.0.1',self._requested_port,
                                  backlog=16,reuse_address=False,reuse_port=False)
            await self._site.start()
            addresses=self._runner.addresses
            require(len(addresses)==1 and len(addresses[0])==2
                    and addresses[0][0]=='127.0.0.1'
                    and type(addresses[0][1]) is int and 0<addresses[0][1]<=65535,
                    'readiness_listener_address')
            self._bound_port=addresses[0][1]
            self._stage='SERVING'
            return self.status()
        except BaseException as exc:
            self._revoked=True;self._stage='FAILED'
            # Caller must invoke close(), or exit if it cannot be confirmed.
            # No hidden retry, no lease release, no ambiguous constructor cleanup.
            if isinstance(exc,(KeyboardInterrupt,SystemExit,asyncio.CancelledError)):raise
            if isinstance(exc,ReadinessRejected):raise
            raise ReadinessRejected('readiness_start_failed') from exc

    def status(self):
        self._owned()
        return {'state':self._stage,'host':'127.0.0.1','port':self._bound_port,
                'scope':'native_storage_readiness_only','listenerBindConfirmed':self._bound_port is not None and not self._http_gone,
                'httpCleanupPending':not self._http_gone,
                'readinessRevoked':self._revoked,'successfulStorageObservations':self._probes,
                'storageReadinessMustBeQueried':True,'agentRoutesEnabled':False,
                'runtimeAdmissionAuthorized':False,'fullHermesGatewayStarted':False,
                'callerLeaseMayBeReleased':self._stage=='CLOSED'}

    def _response(self,status,body):
        response=self._web_module.json_response(body,status=status,headers={
            'Cache-Control':'no-store','Pragma':'no-cache','X-Content-Type-Options':'nosniff'})
        # No persistent/pipelined diagnostic connection survives an outcome.
        response.force_close()
        return response

    async def _handle(self,request):
        # aiohttp owns parsing and protocol limits. No user callback is invoked.
        try:self._owned()
        except Exception:return self._response(503,{'status':'unavailable'})
        values=request.headers.getall('Authorization',[])
        if (not self._authorization or len(values)!=1 or not isinstance(values[0],str)
                or not values[0].isascii() or len(values[0])>128
                or not hmac.compare_digest(values[0].encode('ascii'),self._authorization)):
            return self._response(401,{'status':'unauthorized'})
        hosts=request.headers.getall('Host',[])
        if (hosts!=['127.0.0.1:'+str(self._bound_port)] or 'Origin' in request.headers
                or request.content_length not in (None,0) or request.can_read_body):
            return self._response(400,{'status':'invalid_request'})
        if request.raw_path not in ('/health/live','/health/ready'):
            return self._response(404,{'status':'not_found'})
        if request.method!='GET':return self._response(405,{'status':'method_not_allowed'})
        if self._stage not in ('SERVING','REVOKED'):
            return self._response(503,{'status':'stopping','scope':'native_storage_readiness_only'})
        if request.raw_path=='/health/live':
            return self._response(200,{'status':'alive','scope':'process_liveness_only',
                                       'runtimeAdmissionAuthorized':False})
        if not self._revoked:
            try:self._probe()
            except Exception:
                self._revoked=True;self._stage='REVOKED'
        ready=not self._revoked
        return self._response(200 if ready else 503,{
            'status':'ready' if ready else 'not_ready','storageReady':ready,
            'scope':'native_storage_readiness_only','runtimeAdmissionAuthorized':False,
            'agentRoutesEnabled':False})

    async def close(self):
        self._owned()
        if self._stage=='CLOSED':return self.status()
        require(self._stage in ('NEW','FAILED','SERVING','REVOKED','HTTP_CLOSED'),
                'readiness_close_unknown_or_active')
        self._revoked=True;self._stage='STOPPING'  # Before the first await/effect.
        if not self._http_gone:
            try:
                # Official aiohttp runner shutdown: stop sites then drain handlers.
                await self._runner.cleanup()
                self._runner=self._site=None;self._http_gone=True
            except BaseException as exc:
                self._stage='CLOSE_UNKNOWN'
                if isinstance(exc,(KeyboardInterrupt,SystemExit,asyncio.CancelledError)):raise
                raise ReadinessRejected('readiness_http_close_unconfirmed') from exc
        self._stage='HTTP_CLOSED'
        # A109 refuses active writers/transactions and uncertain constructors.
        # On refusal HTTP stays CLOSED; caller ownership remains held for drain.
        try:self._stores.close()
        except BaseException as exc:
            if isinstance(exc,(KeyboardInterrupt,SystemExit,asyncio.CancelledError)):raise
            raise ReadinessRejected('readiness_storage_close_refused') from exc
        require(self._stores.status()['callerLeaseMayBeReleased'] is True,
                'readiness_storage_close_unconfirmed')
        self._stage='CLOSED';self._authorization=b''
        return self.status()
